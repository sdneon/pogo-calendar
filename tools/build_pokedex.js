'use strict';
// Build public/pokedex.js: species names (from ../pogo-stats-comp/data.js) plus
// legendary / mythical / ultra-beast class (from the PokeMiners game master).
// Usage: node tools/build_pokedex.js [path/to/game_master.json]

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const STATS_DATA = path.join(ROOT, '..', 'pogo-stats-comp', 'data.js');
const GM_URL = 'https://raw.githubusercontent.com/PokeMiners/game_masters/master/latest/latest.json';
const CLASS = { POKEMON_CLASS_LEGENDARY: 'L', POKEMON_CLASS_MYTHIC: 'M', POKEMON_CLASS_ULTRA_BEAST: 'U' };

async function main() {
  global.window = {};
  require(STATS_DATA);
  const names = new Map();
  const forms = new Map(); // dex -> [[form, atk, def, sta], ...]
  for (const p of window.POGO_DATA.pokemon) {
    if (!names.has(p.id)) names.set(p.id, p.n);
    if (!forms.has(p.id)) forms.set(p.id, []);
    forms.get(p.id).push([p.f, ...p.s, p.t]);
  }
  const cpm = window.POGO_DATA.cpm;

  const gm = process.argv[2]
    ? JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
    : await (await fetch(GM_URL)).json();
  const cls = new Map();
  const temp = new Map(); // dex -> {MEGA|MEGA_X|MEGA_Y|PRIMAL: [types]}
  const typeName = (t) => t && t.replace('POKEMON_TYPE_', '').toLowerCase().replace(/^./, (c) => c.toUpperCase());
  for (const t of gm) {
    const ps = t.data && t.data.pokemonSettings;
    const m = /^V0*(\d+)_POKEMON_/.exec(t.templateId || '');
    if (!ps || !m) continue;
    if (CLASS[ps.pokemonClass]) cls.set(+m[1], CLASS[ps.pokemonClass]);
    for (const o of ps.tempEvoOverrides || []) {
      const k = /TEMP_EVOLUTION_(\w+)/.exec(o.tempEvoId || '')?.[1];
      if (!k || !o.typeOverride1) continue;
      if (!temp.has(+m[1])) temp.set(+m[1], {});
      temp.get(+m[1])[k] = [typeName(o.typeOverride1), typeName(o.typeOverride2)].filter(Boolean);
    }
  }

  const species = [...names].sort((a, b) => a[0] - b[0]).map(([id, n]) => [id, n, cls.get(id) || '', forms.get(id), temp.get(id) || 0]);
  const out = `// Generated by tools/build_pokedex.js - do not edit by hand.\n`
    + `// [dex, name, class, [[form, atk, def, sta, types], ...], {MEGA|MEGA_X|MEGA_Y|PRIMAL: types} or 0];\n`
    + `// class L = legendary, M = mythical, U = ultra beast, '' = none.\n`
    + `window.POGO_DEX = ${JSON.stringify(species)};\n`
    + `// CP multipliers for raid / Max Battle catches (level 20) and weather-boosted catches (level 25).\n`
    + `window.POGO_CPM = ${JSON.stringify({ 20: cpm[19], 25: cpm[24] })};\n`;
  fs.writeFileSync(path.join(ROOT, 'public', 'pokedex.js'), out);
  console.log(`${species.length} species, ${cls.size} with a class`);
}

main().catch((e) => { console.error(e); process.exit(1); });
